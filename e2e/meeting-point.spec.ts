import { test, expect } from '@playwright/test'
import { mockKakao } from './helpers/mockKakao'
import { completeProfile } from './helpers/profile'

test.use({ timezoneId: 'Asia/Seoul' })
test('map click, dragged pin, meeting detail, time and unlimited budget survive editing', async ({ page }) => {
  await mockKakao(page)
  await page.goto('/')
  await page.getByRole('button', { name: '게스트로 시작하기' }).click()
  await completeProfile(page)
  await page.getByRole('button', { name: '＋ 파티 만들기' }).click()
  await expect(page.getByRole('button', { name: '장소 검색', exact: true })).toBeEnabled()
  await page.locator('.place-map').click({ position: { x: 60, y: 100 } })
  await expect(page.locator('.selected-address')).toContainText('서울 중구 세종대로 110')
  const marker = page.getByRole('button', { name: '지도 핀' }), bounds = (await marker.boundingBox())!
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2); await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width / 2 + 30, bounds.y + bounds.height / 2 + 20, { steps: 5 }); await page.mouse.up()
  await page.getByLabel('상세 만날 위치').fill('정문 앞 벤치')
  await page.locator('.meeting-conditions summary').click()
  await page.getByLabel('파티 이름', { exact: true }).fill('정확한 위치 모임')
  await page.getByLabel('약속 시간 (선택)').fill('2026-10-26T12:30')
  await page.getByRole('combobox', { name: '1인 예산', exact: true }).selectOption('none')
  const posted = page.waitForRequest(request => request.method() === 'POST' && new URL(request.url()).pathname === '/api/v1/parties')
  await page.getByRole('button', { name: '이 장소로 파티 만들기' }).click()
  const body = (await posted).postDataJSON()
  expect(body.location).toEqual({ latitude: 37.5672, longitude: 126.9791, address: '서울 중구 세종대로 110\n만날 위치: 정문 앞 벤치' })
  expect(body.scheduledAt).toBe('2026-10-26T03:30:00.000Z')
  expect(body.budgetPerPerson).toBeNull()
  await expect(page.locator('.waiting-location')).toContainText('정문 앞 벤치')
  await page.reload()
  await expect(page.locator('.waiting-conditions').last()).toContainText('예산 제한 없음')
  await page.getByRole('button', { name: '장소·조건 변경' }).click()
  await expect(page.getByLabel('상세 만날 위치')).toHaveValue('정문 앞 벤치')
  await page.locator('.meeting-conditions summary').click()
  await expect(page.getByLabel('약속 시간 (선택)')).toHaveValue('2026-10-26T12:30')
  await expect(page.getByRole('combobox', { name: '1인 예산', exact: true })).toHaveValue('none')
  await page.getByLabel('상세 만날 위치').fill('후문 1층')
  await page.getByRole('button', { name: '변경 내용 저장' }).click()
  await expect(page.locator('.waiting-location')).toContainText('후문 1층')
  await expect(page.locator('.waiting-location')).not.toContainText('정문 앞 벤치')
})
