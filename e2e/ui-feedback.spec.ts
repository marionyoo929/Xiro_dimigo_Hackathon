import { test, expect } from '@playwright/test'
import { completeProfile } from './helpers/profile'

for (const width of [375, 402]) test(`home, restrictions, place and waiting room at ${width}px`, async ({ browser, baseURL }) => {
  const context = await browser.newContext({ viewport: { width, height: 812 } })
  const page = await context.newPage()
  const errors: string[] = []
  const noHorizontalOverflow = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(baseURL!)
  await page.getByRole('button', { name: '이메일로 로그인하기' }).click()
  await page.getByLabel('닉네임', { exact: true }).fill(`피드백 ${width}`)
  await page.getByRole('button', { name: '시작하기', exact: true }).click()
  await completeProfile(page)
  await expect(page.locator('.home-screen .welcome-card h1')).toHaveText('싫은 건 빼고,맛있는 것만 남겨요')
  await expect(page.locator('.home-screen .welcome-main img')).toBeVisible()
  await expect(page.locator('.home-create-button')).toHaveCSS('background-color', 'rgb(254, 146, 146)')
  await expect(page.getByText('함께 고르는 즐거움')).toHaveCount(0)
  const buttonCenter = await page.locator('.home-create-button').evaluate(button => {
    const label = button.querySelector('span')!.getBoundingClientRect(), bounds = button.getBoundingClientRect()
    return { x: Math.abs(label.x + label.width / 2 - bounds.x - bounds.width / 2), y: Math.abs(label.y + label.height / 2 - bounds.y - bounds.height / 2) }
  })
  expect(buttonCenter.x).toBeLessThan(1)
  expect(buttonCenter.y).toBeLessThan(1)
  await noHorizontalOverflow()
  const homeBoxes = await Promise.all(['.welcome-main h1', '.welcome-main img'].map(selector => page.locator(selector).boundingBox()))
  expect(homeBoxes[0]!.x + homeBoxes[0]!.width).toBeLessThanOrEqual(homeBoxes[1]!.x)
  await page.screenshot({ path: `test-results/ui-home-${width}.png`, fullPage: true })
  await page.getByRole('button', { name: '내 식사 제한 관리' }).click()
  await expect(page.getByRole('heading', { name: '먹을 수 없는 재료가 있나요?' })).toBeVisible()
  await expect(page.locator('.dietary-group')).toHaveCount(6)
  await page.getByRole('checkbox', { name: '돼지고기' }).check()
  await page.getByRole('combobox', { name: '돼지고기 제한 사유' }).selectOption('INGREDIENT_AVOIDANCE')
  await page.getByRole('button', { name: '식사 제한 저장' }).click()
  await expect(page.getByText('저장했어요.', { exact: false })).toBeVisible()
  await noHorizontalOverflow()
  await page.screenshot({ path: `test-results/ui-restrictions-${width}.png`, fullPage: true })
  await page.getByRole('button', { name: /돌아가기/ }).click()
  await page.getByRole('button', { name: '내 식사 제한 관리' }).click()
  await expect(page.getByRole('checkbox', { name: '돼지고기' })).toBeChecked()
  await expect(page.getByRole('combobox', { name: '돼지고기 제한 사유' })).toHaveValue('INGREDIENT_AVOIDANCE')
  await page.getByRole('button', { name: /돌아가기/ }).click()
  await page.getByRole('button', { name: '＋ 파티 만들기' }).click()
  await expect(page.getByText('카카오 지도 JavaScript 키가 설정되지 않았어요.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: '서울시청', exact: true }).click()
  await expect(page.locator('.selected-place-heading h2')).toHaveText('서울시청')
  await expect(page.locator('.selected-place-heading>span')).toHaveCount(0)
  await page.locator('#search-radius').fill('600')
  await expect(page.locator('#search-radius')).toHaveValue('600')
  await page.locator('.meeting-conditions summary').click()
  await page.getByLabel('파티 이름').fill(`모임 ${width}`)
  await noHorizontalOverflow()
  await page.screenshot({ path: `test-results/ui-place-${width}.png`, fullPage: true })
  await page.getByRole('button', { name: '이 장소로 파티 만들기' }).click()
  await expect(page.getByRole('heading', { name: '함께 먹을 준비됐나요?' })).toBeVisible()
  await expect(page.getByText('참가자 1/8')).toBeVisible()
  await expect(page.locator('.waiting-restrictions')).toContainText('돼지고기')
  await expect(page.locator('.restriction-confirm-button')).toHaveCSS('background-color', 'rgb(254, 146, 146)')
  await page.getByRole('button', { name: '최신 식사 제한 확인' }).click()
  await expect(page.getByText('제한 확인 완료')).toBeVisible()
  await noHorizontalOverflow()
  await page.screenshot({ path: `test-results/ui-waiting-${width}.png`, fullPage: true })
  expect(errors).toEqual([])
  await context.close()
})
